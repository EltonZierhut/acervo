module Mentoring
  # Perguntas que norteiam a mentoria, copiadas para cada mentoria nova (spec 010, research.md §2).
  module SuggestedQuestions
    ALL = [
      "Qual é o seu objetivo principal com esta mentoria? O que precisa ser verdade ao final dela?",
      "Onde você está hoje na carreira e onde quer estar daqui a 1 e a 3 anos?",
      "Quais pontos fortes você quer aproveitar mais?",
      "Quais habilidades ou comportamentos você quer desenvolver?",
      "Quais desafios ou obstáculos estão travando seu crescimento agora?",
      "O que você já tentou para resolver esses desafios, e o que aconteceu?",
      "Como você aprende melhor? (exemplos práticos, leitura, conversas, desafios…)",
      "Como você prefere receber feedback?",
      "O que você espera do seu mentor, e o que ele pode esperar de você?",
      "Com que frequência e por quanto tempo vocês vão se encontrar? Por quantos meses?",
      "Como você vai saber que a mentoria deu certo? Quais sinais ou números vai observar?",
      "Há assuntos fora do escopo ou combinados de confidencialidade a definir?"
    ].freeze
  end
end
